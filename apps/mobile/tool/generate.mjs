// Generates the Dart files the Flutter app shares with the web, so there is one source of truth:
//   lib/core/currencies.g.dart  from packages/core (CURRENCIES)
//   lib/l10n/strings.g.dart     from apps/web/lib/i18n.ts (en + ar copy)
// Run from the repo root after `npm run build:packages`:  node apps/mobile/tool/generate.mjs
// CI runs it and fails if the committed files are out of date.
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const mobile = join(root, 'apps/mobile');
const header = (from) =>
  `// GENERATED by apps/mobile/tool/generate.mjs from ${from}.\n// Do not edit by hand: change the source and run \`node apps/mobile/tool/generate.mjs\` at the repo root.\n`;

/** A Dart single-quoted string literal. */
const dq = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

// ---- currencies -------------------------------------------------------------------------------
const core = await import(pathToFileURL(join(root, 'packages/core/dist/index.js')).href);
const cur = core.CURRENCIES.map(
  (c) =>
    `  CurrencyInfo(code: ${dq(c.code)}, decimals: ${c.decimals}, en: ${dq(c.en)}, ar: ${dq(c.ar)}${c.arSymbol ? `, arSymbol: ${dq(c.arSymbol)}` : ''}),`,
).join('\n');
writeFileSync(
  join(mobile, 'lib/core/currencies.g.dart'),
  `${header('packages/core/src/money.ts')}
class CurrencyInfo {
  const CurrencyInfo({required this.code, required this.decimals, required this.en, required this.ar, this.arSymbol});
  final String code;
  final int decimals;
  final String en;
  final String ar;

  /// Symbol shown in Arabic UI; English UI shows the ISO code.
  final String? arSymbol;

  String name(String lang) => lang == 'ar' ? ar : en;
}

/// Decimals follow ISO 4217, except IQD/LBP/SYP/IDR where nobody uses the minor unit.
const currencies = <CurrencyInfo>[
${cur}
];
`,
);

// ---- strings ----------------------------------------------------------------------------------
const src = readFileSync(join(root, 'apps/web/lib/i18n.ts'), 'utf8').replace(/^const (en|ar)\b/gm, 'export const $1');
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const tmp = mkdtempSync(join(tmpdir(), 'nn-i18n-'));
const file = join(tmp, 'i18n.mjs');
writeFileSync(file, js);
const { en, ar } = await import(pathToFileURL(file).href);
rmSync(tmp, { recursive: true, force: true });

const keys = Object.keys(en);
const missing = keys.filter((k) => !(k in ar));
if (missing.length) throw new Error(`Arabic is missing: ${missing.join(', ')}`);
const camel = (k) => k.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const map = (d) => keys.map((k) => `  ${dq(k)}: ${dq(d[k])},`).join('\n');

mkdirSync(join(mobile, 'lib/l10n'), { recursive: true });
writeFileSync(
  join(mobile, 'lib/l10n/strings.g.dart'),
  `${header('apps/web/lib/i18n.ts')}
/// Every piece of copy in the app, in English and Arabic. The web uses the same words.
class NNStrings {
  const NNStrings._(this.lang, this._m);

  /// 'en' or 'ar'.
  final String lang;
  final Map<String, String> _m;

  static const en = NNStrings._('en', _en);
  static const ar = NNStrings._('ar', _ar);
  static NNStrings of(String lang) => lang == 'ar' ? ar : en;

  bool get isRtl => lang == 'ar';

  /// Look a key up by name, e.g. 'mode_equal' or 'cat_food'. Falls back to English, then the key.
  String raw(String key) => _m[key] ?? _en[key] ?? key;

  /// Fill {placeholders}: s.fill(s.paidX, {'name': 'Sara', 'amount': 'AED 5.00'}).
  String fill(String template, Map<String, Object> params) {
    var out = template;
    params.forEach((k, v) => out = out.split('{\$k}').join('\$v'));
    return out;
  }

${keys.map((k) => `  String get ${camel(k)} => _m[${dq(k)}]!;`).join('\n')}
}

const _en = <String, String>{
${map(en)}
};

const _ar = <String, String>{
${map(ar)}
};
`,
);

console.log(`currencies: ${core.CURRENCIES.length}, strings: ${keys.length} keys`);
