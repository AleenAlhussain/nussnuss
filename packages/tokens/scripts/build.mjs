// Generates the design tokens for both apps from tokens.json:
//   dist/tokens.css                         CSS variables (light, dark, frosted glass, reduced motion)
//   ../../apps/mobile/lib/design/tokens.g.dart   Dart constants for Flutter
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { hexToRgb, kebab, rgba, root, stiffness, tokens } from './lib.mjs';

const { color, glass, type, font, space, radius, motion, layout } = tokens;
const looks = tokens.looks ?? {};
const displayFor = new Set(font.displayFor ?? []);
const roles = Object.keys(color.light);

// ---------- CSS ----------
const colorVars = (mode) => roles.map((k) => `  --nn-${kebab(k)}: ${color[mode][k]};`).join('\n');
const lookVars = (name, mode) =>
  Object.entries(looks[name]?.[mode] ?? {})
    .filter(([k]) => roles.includes(k))
    .map(([k, v]) => `  --nn-${kebab(k)}: ${v};`)
    .join('\n');
const white = (a) => `rgba(255, 255, 255, ${a})`;
const glassVars = (variant, mode) => {
  const g = glass[variant][mode];
  const v = glass[variant];
  // Tinted glass takes its colour from the look (accentSoft), so Saffron tints amber and the default violet.
  const fill = v.fillRole ? `color-mix(in srgb, var(--nn-${kebab(v.fillRole)}) ${Math.round(g.fillAlpha * 100)}%, transparent)` : rgba(g.fill, g.fillAlpha);
  const out = [`  --nn-glass-fill: ${fill};`, `  --nn-glass-blur: ${v.blur}px;`, `  --nn-glass-saturate: ${v.saturation};`];
  if (g.highlight) out.push(`  --nn-glass-highlight: ${rgba(g.highlight, g.highlightAlpha)};`);
  if (g.shadow) out.push(`  --nn-glass-shadow: 0 8px 32px ${rgba(g.shadow, g.shadowAlpha)};`);
  if (variant === 'frosted') {
    out.push(
      `  --nn-glass-highlight: transparent;`,
      `  --nn-glass-border: var(--nn-separator);`,
      `  --nn-glass-edge: linear-gradient(var(--nn-separator), var(--nn-separator));`,
    );
  } else {
    const e = glass.edge[mode];
    out.push(
      `  --nn-glass-border: ${white(e.hairline)};`,
      `  --nn-glass-edge: linear-gradient(135deg, ${white(e.top)}, ${white(e.hairline)} 45%);`,
    );
  }
  return out.join('\n');
};
const ind = (s) => s.replace(/^/gm, '  ');
const ambientVar = (mode) => {
  const a = tokens.ambient[mode];
  return `  --nn-ambient: radial-gradient(120% 60% at var(--nn-ambient-start, 0%) 0%, color-mix(in srgb, var(--nn-accent) ${Math.round(a.accentAlpha * 100)}%, transparent), transparent 70%), radial-gradient(90% 45% at var(--nn-ambient-end, 100%) 0%, color-mix(in srgb, var(--nn-highlight) ${Math.round(a.highlightAlpha * 100)}%, transparent), transparent 70%);`;
};

const typeVars = Object.entries(type)
  .map(([k, t]) => {
    const n = kebab(k);
    return [
      `  --nn-type-${n}-size: ${t.size / 16}rem;`,
      `  --nn-type-${n}-line: ${(t.line / t.size).toFixed(4)};`,
      `  --nn-type-${n}-weight: ${t.weight};`,
      `  --nn-type-${n}-tracking: ${(t.tracking / t.size).toFixed(4)}em;`,
      `  --nn-type-${n}-family: ${displayFor.has(k) ? 'var(--nn-font-display)' : 'inherit'};`,
    ].join('\n');
  })
  .join('\n');

const spring = (m) => ({ duration: m.response, bounce: Math.max(0, Math.round((1 - m.damping) * 100) / 100) });

const css = `/* GENERATED by packages/tokens/scripts/build.mjs from tokens.json — do not edit by hand. */
:root {
${colorVars('light')}
${glassVars('tinted', 'light')}
${ambientVar('light')}
${typeVars}
  --nn-font: ${font.web};
  --nn-font-ar: ${font.webArabic};
  --nn-font-rounded: ${font.webRounded};
  --nn-font-display: "${font.display}", ${font.web};
${Object.entries(space).map(([k, v]) => `  --nn-space-${kebab(k)}: ${v}px;`).join('\n')}
${Object.entries(radius).map(([k, v]) => `  --nn-radius-${kebab(k)}: ${v}px;`).join('\n')}
${Object.entries(layout).map(([k, v]) => `  --nn-layout-${kebab(k)}: ${v}px;`).join('\n')}
  --nn-fade: ${motion.fadeMs}ms;
  --nn-ease: cubic-bezier(0.32, 0.72, 0, 1);
  --nn-press: ${motion.pressScale};
  --nn-glass-press: ${motion.glassPressScale};
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${ind(colorVars('dark'))}
${ind(glassVars('tinted', 'dark'))}
${ind(ambientVar('dark'))}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${colorVars('dark')}
${glassVars('tinted', 'dark')}
${ambientVar('dark')}
  color-scheme: dark;
}
/* Glass: Clear, by choice. */
:root[data-glass="clear"] {
${glassVars('regular', 'light')}
}
@media (prefers-color-scheme: dark) {
  :root[data-glass="clear"]:not([data-theme="light"]) {
${ind(glassVars('regular', 'dark'))}
  }
}
:root[data-glass="clear"][data-theme="dark"] {
${glassVars('regular', 'dark')}
}
/* Glass: Solid, by choice. */
:root[data-glass="frosted"] {
${glassVars('frosted', 'light')}
}
@media (prefers-color-scheme: dark) {
  :root[data-glass="frosted"]:not([data-theme="light"]) {
${ind(glassVars('frosted', 'dark'))}
  }
}
:root[data-glass="frosted"][data-theme="dark"] {
${glassVars('frosted', 'dark')}
}
/* Glass: Solid, by need. Reduce Transparency, Increase Contrast or no backdrop-filter beat any choice
   (the repeated :root raises specificity above the settings above). */
@media (prefers-reduced-transparency: reduce), (prefers-contrast: more) {
  :root:root:root {
${ind(glassVars('frosted', 'light'))}
  }
}
@media (prefers-reduced-transparency: reduce) and (prefers-color-scheme: dark), (prefers-contrast: more) and (prefers-color-scheme: dark) {
  :root:root:root:not([data-theme="light"]) {
${ind(glassVars('frosted', 'dark'))}
  }
}
@media (prefers-reduced-transparency: reduce), (prefers-contrast: more) {
  :root:root:root[data-theme="dark"] {
${ind(glassVars('frosted', 'dark'))}
  }
}
@supports not ((backdrop-filter: blur(1px)) or (-webkit-backdrop-filter: blur(1px))) {
  :root:root:root {
${ind(glassVars('frosted', 'light'))}
  }
  :root:root:root[data-theme="dark"] {
${ind(glassVars('frosted', 'dark'))}
  }
}
${Object.keys(looks)
  .map((name) => {
    const L = looks[name];
    if (L.onlyDark) {
      return `/* Look: ${name} (always dark) */
:root[data-look="${name}"] {
${colorVars('dark')}
${lookVars(name, 'dark')}
${glassVars('tinted', 'dark')}
${ambientVar('dark')}
  color-scheme: dark;
}
:root[data-look="${name}"][data-glass="clear"] {
${glassVars('regular', 'dark')}
}
:root[data-look="${name}"][data-glass="frosted"] {
${glassVars('frosted', 'dark')}
}
@media (prefers-reduced-transparency: reduce), (prefers-contrast: more) {
  :root:root:root[data-look="${name}"] {
${ind(glassVars('frosted', 'dark'))}
  }
}
@supports not ((backdrop-filter: blur(1px)) or (-webkit-backdrop-filter: blur(1px))) {
  :root:root:root[data-look="${name}"] {
${ind(glassVars('frosted', 'dark'))}
  }
}`;
    }
    return `/* Look: ${name} */
:root[data-look="${name}"] {
${lookVars(name, 'light')}
}
@media (prefers-color-scheme: dark) {
  :root[data-look="${name}"]:not([data-theme="light"]) {
${ind(lookVars(name, 'dark'))}
  }
}
:root[data-look="${name}"][data-theme="dark"] {
${lookVars(name, 'dark')}
}`;
  })
  .join('\n')}
`;

const motionJs = `// GENERATED by packages/tokens/scripts/build.mjs — do not edit by hand.
export const springs = ${JSON.stringify(
  { standard: spring(motion.standard), bouncy: spring(motion.bouncy), gentle: spring(motion.gentle), sheet: spring(motion.sheet) },
  null,
  2,
)};
export const fadeMs = ${motion.fadeMs};
export const layout = ${JSON.stringify(layout)};
`;

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/tokens.css'), css);
writeFileSync(join(root, 'dist/motion.js'), motionJs);
writeFileSync(
  join(root, 'dist/motion.d.ts'),
  `export declare const springs: Record<'standard' | 'bouncy' | 'gentle' | 'sheet', { duration: number; bounce: number }>;\nexport declare const fadeMs: number;\nexport declare const layout: Record<string, number>;\n`,
);

// ---------- Dart ----------
const argb = (hex, alpha = 1) => {
  const [r, g, b] = hexToRgb(hex);
  const a = Math.round(alpha * 255);
  return `Color(0x${[a, r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('').toUpperCase()})`;
};
const fields = roles.map((k) => `  final Color ${k};`).join('\n');
const params = roles.map((k) => `    required this.${k},`).join('\n');
const palette = (mode) => `NNPalette(\n${roles.map((k) => `    ${k}: ${argb(color[mode][k])},`).join('\n')}\n  )`;
const glassStyle = (variant, mode) => {
  const g = glass[variant][mode];
  const v = glass[variant];
  // Tinted: the default look's accentSoft; other looks recompute it from their palette (NNGlass.tintedAlpha).
  const fillHex = v.fillRole ? color[mode][v.fillRole] : g.fill;
  return `NNGlassStyle(
    fill: ${argb(fillHex, g.fillAlpha)},
    highlight: ${g.highlight ? argb(g.highlight, g.highlightAlpha) : 'Color(0x00000000)'},
    shadow: ${g.shadow ? argb(g.shadow, g.shadowAlpha) : 'Color(0x00000000)'},
    blur: ${v.blur.toFixed(1)},
    saturation: ${v.saturation.toFixed(2)},
    bordered: ${variant === 'frosted'},
  )`;
};
const weight = (w) => `FontWeight.w${w}`;
const dartFamily = font.display.replace(/\s+/g, '');
const dartType = Object.entries(type)
  .map(
    ([k, t]) =>
      `  static const ${k} = TextStyle(${displayFor.has(k) ? `fontFamily: '${dartFamily}', ` : ''}fontSize: ${t.size.toFixed(1)}, height: ${(t.line / t.size).toFixed(4)}, fontWeight: ${weight(t.weight)}, letterSpacing: ${t.tracking.toFixed(2)});`,
  )
  .join('\n');
const lookPalettes = Object.entries(looks)
  .flatMap(([name, L]) =>
    ['light', 'dark']
      .filter((mode) => L[mode] && !(L.onlyDark && mode === 'light'))
      .map((mode) => {
        const merged = { ...color[mode], ...L[mode] };
        return `  static const ${name}${mode === 'light' ? 'Light' : 'Dark'} = NNPalette(\n${roles.map((k) => `    ${k}: ${argb(merged[k])},`).join('\n')}\n  );`;
      }),
  )
  .join('\n');
const lookNames = Object.keys(looks);
const dartSprings = ['standard', 'bouncy', 'gentle', 'sheet']
  .map(
    (k) =>
      `  static final ${k} = SpringDescription.withDampingRatio(mass: 1, stiffness: ${stiffness(motion[k].response)}, ratio: ${motion[k].damping.toFixed(2)});\n  static const ${k}Duration = Duration(milliseconds: ${Math.round(motion[k].response * 1000)});`,
  )
  .join('\n');

const dart = `// GENERATED by packages/tokens/scripts/build.mjs from packages/tokens/tokens.json.
// Do not edit by hand: change tokens.json and run \`npm run tokens\` at the repo root.
// ignore_for_file: constant_identifier_names

import 'package:flutter/painting.dart';
import 'package:flutter/physics.dart';

/// Color roles. Same names as the web's --nn-* variables.
class NNPalette {
  const NNPalette({
${params}
  });
${fields}
}

class NNGlassStyle {
  const NNGlassStyle({
    required this.fill,
    required this.highlight,
    required this.shadow,
    required this.blur,
    required this.saturation,
    required this.bordered,
  });

  /// Tint laid over the blurred backdrop.
  final Color fill;

  /// 1px inner highlight along the top edge (light from above).
  final Color highlight;
  final Color shadow;

  /// Gaussian blur sigma-equivalent in logical pixels.
  final double blur;
  final double saturation;

  /// Frosted variants draw a hairline border instead of the highlight.
  final bool bordered;
}

class NNColors {
  static const light = ${palette('light')};
  static const dark = ${palette('dark')};
}

/// Optional looks (sold in Looks). ${lookNames.filter((n) => looks[n].onlyDark).join(', ') || 'None'} ${lookNames.filter((n) => looks[n].onlyDark).length === 1 ? 'is' : 'are'} always dark.
class NNLooks {
${lookPalettes}

  /// Looks that ignore the light/dark setting and are always dark.
  static const alwaysDark = <String>{${lookNames.filter((n) => looks[n].onlyDark).map((n) => `'${n}'`).join(', ')}};
}

/// The soft light behind every screen (accent at the top start, highlight at the top end).
class NNAmbient {
  static const accentAlphaLight = ${tokens.ambient.light.accentAlpha};
  static const highlightAlphaLight = ${tokens.ambient.light.highlightAlpha};
  static const accentAlphaDark = ${tokens.ambient.dark.accentAlpha};
  static const highlightAlphaDark = ${tokens.ambient.dark.highlightAlpha};
}

/// Font family for amounts and big titles, bundled in assets/fonts.
const nnDisplayFamily = '${dartFamily}';

class NNGlass {
  static const regularLight = ${glassStyle('regular', 'light')};
  static const regularDark = ${glassStyle('regular', 'dark')};
  static const frostedLight = ${glassStyle('frosted', 'light')};
  static const frostedDark = ${glassStyle('frosted', 'dark')};

  /// Tinted (the default): the palette's ${glass.tinted.fillRole} at these opacities.
  static const tintedLight = ${glassStyle('tinted', 'light')};
  static const tintedDark = ${glassStyle('tinted', 'dark')};
  static const tintedAlphaLight = ${glass.tinted.light.fillAlpha};
  static const tintedAlphaDark = ${glass.tinted.dark.fillAlpha};

  /// Hairline edge on Clear and Tinted glass: white at [edgeHairline…], brighter ([edgeTop…]) at the top-left.
  static const edgeTopLight = ${argb('#FFFFFF', glass.edge.light.top)};
  static const edgeHairlineLight = ${argb('#FFFFFF', glass.edge.light.hairline)};
  static const edgeTopDark = ${argb('#FFFFFF', glass.edge.dark.top)};
  static const edgeHairlineDark = ${argb('#FFFFFF', glass.edge.dark.hairline)};
}

/// iOS text styles at the default (Large) Dynamic Type size; Flutter scales them with the system text scale.
class NNType {
${dartType}
}

class NNSpace {
${Object.entries(space).map(([k, v]) => `  static const double ${k} = ${v.toFixed(1)};`).join('\n')}
}

class NNRadius {
${Object.entries(radius).map(([k, v]) => `  static const double ${k} = ${v.toFixed(1)};`).join('\n')}
}

class NNLayout {
${Object.entries(layout).map(([k, v]) => `  static const double ${k} = ${v.toFixed(1)};`).join('\n')}
}

/// Springs from SwiftUI response / damping. With "Reduce Motion" on, use [fade] instead.
class NNMotion {
${dartSprings}
  static const fade = Duration(milliseconds: ${motion.fadeMs});

  /// Pressed solid buttons scale down to [pressScale]; pressed glass controls swell to [glassPressScale].
  static const pressScale = ${motion.pressScale};
  static const glassPressScale = ${motion.glassPressScale};
}
`;

const dartPath = join(root, '../../apps/mobile/lib/design/tokens.g.dart');
mkdirSync(join(dartPath, '..'), { recursive: true });
writeFileSync(dartPath, dart);
console.log('tokens → dist/tokens.css, dist/motion.js, apps/mobile/lib/design/tokens.g.dart');
